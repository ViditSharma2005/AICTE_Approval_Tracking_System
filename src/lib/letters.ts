export type GeneratedLetter = {
  type: LetterType;
  template: string;
  subject: string;
  html: string;
  applicationId: string;
  refNumber: string;
};

/**
 * Draft a letter from live case data. Pure read + render: nothing is persisted
 * and nothing is dispatched until an officer marks it as sent.
 */
export async function generateLetter(
  type: LetterType,
  applicationId: string,
  officer?: { name: string; designation?: string | null },
): Promise<GeneratedLetter> {
  const app = await db.application.findUniqueOrThrow({
    where: { id: applicationId },
    include: {
      institution: { select: { name: true, city: true, state: true } },
      region: { select: { name: true, code: true } },
      assignedTo: { select: { name: true, designation: true } },
      undertakings: { orderBy: { dueAt: "asc" } },
    },
  });

  const route = parseStringArray(app.routeSnapshot);
  const today = new Date();
  const academicYear = `${today.getFullYear()}-${String((today.getFullYear() + 1) % 100).padStart(2, "0")}`;

  const deficiencies = app.undertakings
    .filter((u) => u.phase === "PRE")
    .map((u) => ({ title: u.title, description: u.description, dueAt: fmtDate(u.dueAt) }));

  const conditions = app.undertakings
    .filter((u) => u.phase === "POST")
    .map((u) => ({ title: u.title, description: u.description, dueAt: fmtDate(u.dueAt) }));

  const overdue = app.undertakings
    .filter((u) => ["PENDING", "OVERDUE", "ESCALATED"].includes(u.status) && daysUntil(u.dueAt) < 0)
    .map((u) => ({ title: u.title, dueAt: fmtDate(u.dueAt), daysOver: Math.abs(daysUntil(u.dueAt)) }));

  const context = {
    refNumber: app.refNumber,
    programme: app.programName || app.type.replace(/_/g, " "),
    institution: app.institution,
    region: app.region,
    submittedAt: fmtDate(app.submittedAt),
    today: fmtDate(today),
    academicYear,
    stage: stageShort(app.currentStage),
    route: route.join(" → "),
    responseDays: 15,
    deficiencies,
    conditions,
    overdue,
    officerName: officer?.name ?? app.assignedTo?.name ?? "Scrutiny Officer",
    officerDesignation: officer?.designation ?? app.assignedTo?.designation ?? "For and on behalf of the Council",
    subject:
      type === "DEFICIENCY_NOTICE"
        ? `Deficiency observed in application ${app.refNumber}`
        : type === "SHOW_CAUSE"
          ? `Show cause notice in respect of application ${app.refNumber}`
          : `Conditional approval for ${app.programName || "the programme"} — ${academicYear}`,
  };

  const meta = LETTER_META[type];
  const html = compile(meta.template)(context);

  return {
    type,
    template: meta.template,
    // Subject is plain text (mail header / audit line), so it is rendered unescaped.
    subject: Handlebars.compile(meta.subject, { noEscape: true })(context),
    html,
    applicationId: app.id,
    refNumber: app.refNumber,
  };
}

/** Due date quoted in a freshly drafted notice. */
export function letterResponseDueDate(from = new Date(), days = 15): Date {
  return addDays(from, days);
}
