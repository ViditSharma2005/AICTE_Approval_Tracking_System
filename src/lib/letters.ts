export const LETTER_TEMPLATES: Record<string, string> = {
  "deficiency-notice.hbs": DEFICIENCY_NOTICE_HBS,
  "show-cause.hbs": SHOW_CAUSE_HBS,
  "conditional-approval.hbs": CONDITIONAL_APPROVAL_HBS,
};

const compiled = new Map<string, Handlebars.TemplateDelegate>();
function compile(templateName: string): Handlebars.TemplateDelegate {
  let fn = compiled.get(templateName);
  if (!fn) {
    fn = Handlebars.compile(LETTER_TEMPLATES[templateName] ?? "");
    compiled.set(templateName, fn);
  }
  return fn;
}

