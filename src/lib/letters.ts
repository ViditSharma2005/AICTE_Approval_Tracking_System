/**
 * Feature 8 — auto-drafted letters.
 *
 * The system DRAFTS. A human SENDS. There is deliberately no code path that
 * emails, dispatches or otherwise issues a letter on its own: a letter only
 * becomes SENT when an officer has reviewed it and clicked "Mark as Sent",
 * which writes an audit entry naming them.
 *
 * The templates are Handlebars sources kept inline so they travel with the
 * Next.js bundle (files outside the module graph are not traced by the build).
 */

