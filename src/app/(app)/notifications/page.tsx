import Link from "next/link";
import { requireUser } from "@/lib/session";
import { db } from "@/lib/db";
import { PageHeader } from "@/components/app-shell";
import { Card, EmptyState, Pill } from "@/components/ui";
import { SubmitButton } from "@/components/client";
import { markAllReadAction, markReadAction } from "@/app/actions/misc";
import { Bell, Inbox } from "lucide-react";

export const dynamic = "force-dynamic";

const TYPE_TONE: Record<string, "blue" | "amber" | "red" | "green" | "indigo" | "slate" | "violet"> = {
  ESCALATION: "red",
  SLA_REMINDER: "amber",
  UNDERTAKING_REMINDER: "amber",
  UNDERTAKING_OVERDUE: "red",
  DOC_EXPIRY: "amber",
  DOC_EXPIRED: "red",
  EVC_OVERDUE: "red",
  DECISION: "green",
  STAGE_CHANGE: "indigo",
  NEW_APPLICATION: "blue",
  ASSIGNED: "violet",
};

export default async function NotificationsPage() {
  const user = await requireUser();

  const notifications = await db.notification.findMany({
    where: { userId: user.id },
    orderBy: [{ read: "asc" }, { createdAt: "desc" }],
    take: 100,
  });

  const unread = notifications.filter((n) => !n.read).length;

  return (
    <div>
      <PageHeader
        title="Notifications"
        subtitle={`${notifications.length} message(s) · ${unread} unread`}
        actions={
          unread ? (
            <form action={markAllReadAction}>
              <SubmitButton className="btn-secondary btn-sm" pendingLabel="Marking…">
                Mark all as read
              </SubmitButton>
            </form>
          ) : null
        }
      />

      <Card padded={false}>
        {notifications.length ? (
          <ul className="divide-y divide-slate-100">
            {notifications.map((n) => (
              <li key={n.id} className={n.read ? "" : "bg-indigo-50/40"}>
                <div className="flex items-start gap-3 px-5 py-4">
                  <span className="mt-0.5">
                    <Pill tone={TYPE_TONE[n.type] ?? "slate"}>{n.type.replace(/_/g, " ")}</Pill>
                  </span>
                  <div className="min-w-0 flex-1">
                    <p className="text-sm font-semibold text-ink">
                      {n.link ? (
                        <Link href={n.link} className="hover:underline">
                          {n.title}
                        </Link>
                      ) : (
                        n.title
                      )}
                    </p>
                    <p className="mt-0.5 text-xs leading-relaxed text-ink-soft">{n.body}</p>
                    <p className="mt-1 text-[11px] text-ink-faint">
                      {new Date(n.createdAt).toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" })}
                    </p>
                  </div>
                  {!n.read ? (
                    <form action={markReadAction}>
                      <input type="hidden" name="id" value={n.id} />
                      <SubmitButton className="btn-ghost btn-sm" pendingLabel="…">
                        Mark read
                      </SubmitButton>
                    </form>
                  ) : null}
                </div>
              </li>
            ))}
          </ul>
        ) : (
          <div className="p-5">
            <EmptyState
              icon={<Bell className="h-7 w-7" />}
              title="No notifications yet"
              hint="Reminders, escalations and stage changes land here automatically."
            />
          </div>
        )}
      </Card>

      <div className="mt-4 flex items-start gap-2 rounded-xl border border-slate-200 bg-white p-4">
        <Inbox className="mt-0.5 h-4 w-4 shrink-0 text-slate-400" />
        <p className="text-xs leading-relaxed text-ink-soft">
          Notifications are generated by the deadline engine, not by users. Reminders fire before a deadline
          (7 / 2 / 0 days for undertakings, 90 / 60 / 30 / 7 / 0 for documents), and escalations fire after it.
        </p>
      </div>
    </div>
  );
}
